"""The tax package is byte-identical to v0.1.31's on every corpus (PERF plan §0 invariant 2,
§6.1 "Tax-sheet extraction").

The three sheets' row selection moved into ``portfolio/period_close.py`` so a month or year close
ties out with the package sheet by sheet. The package itself must not move a byte: every member
of every year's package of every corpus is compared with the committed v0.1.31 reference
(``tests/reference/payloads/<corpus>/tax_<year>/``, generated by v0.1.31's own code). A refused
package (``rich_refusals``: the strict replay meets an unreadable action) still refuses with the
reference's sentence.
"""

from __future__ import annotations

import io
import json
import sqlite3
import zipfile
from collections.abc import Iterator
from pathlib import Path

import pytest

from portfolio_dash.export.tax import build_tax_package_zip
from portfolio_dash.portfolio.cost_basis import UnbookableLedgerError
from tests.reference.corpora import CORPORA, CORPUS_NAMES, TEMPLATE_DIR_NAME, copy_corpus, open_db

_PAYLOADS = Path(__file__).resolve().parents[1] / "reference" / "payloads"


def _years(name: str) -> list[int]:
    manifest = json.loads((_PAYLOADS / "manifest.json").read_bytes())
    years: list[int] = manifest["corpora"][name]["tax_years"]
    return years


@pytest.fixture(params=CORPUS_NAMES)
def corpus(request: pytest.FixtureRequest, tmp_path_factory: pytest.TempPathFactory
           ) -> Iterator[tuple[str, sqlite3.Connection]]:
    name: str = request.param
    base = tmp_path_factory.getbasetemp() / TEMPLATE_DIR_NAME
    db = copy_corpus(name, base, tmp_path_factory.mktemp(f"tax-{name}") / f"{name}.db")
    conn = open_db(db.path)
    try:
        yield name, conn
    finally:
        conn.close()


def test_every_member_of_every_package_is_v0131s(corpus: tuple[str, sqlite3.Connection]) -> None:
    name, conn = corpus
    spec = CORPORA[name]
    years = _years(name)
    assert years, f"{name}: no tax year to pin"
    for year in years:
        ref_dir = _PAYLOADS / name / f"tax_{year}"
        refused = ref_dir / "response.json"
        if refused.exists():
            body = json.loads(refused.read_bytes())
            assert body["status"] == 422, f"{name} {year}"
            with pytest.raises(UnbookableLedgerError) as caught:
                build_tax_package_zip(conn, now=spec.now, year=year,
                                      reporting=spec.reporting)
            assert str(caught.value) == body["body"]["error"]["message"], f"{name} {year}"
            continue
        art = build_tax_package_zip(conn, now=spec.now, year=year,
                                    reporting=spec.reporting)
        with zipfile.ZipFile(io.BytesIO(art.content)) as zf:
            members = {info.filename: zf.read(info) for info in zf.infolist()}
        expected = sorted(p.name for p in ref_dir.iterdir())
        assert sorted(members) == expected, f"{name} {year}"
        for member, data in members.items():
            assert data == (ref_dir / member).read_bytes(), f"{name} {year} {member}"
